package emit

import (
	"bufio"
	"fmt"
	"io"
)

func init() { Register(LangGo, goGenerator{}) }

// goGenerator emits a Go source file holding the payload in a byte slice.
//
// A []byte variable rather than a string constant is deliberate: the data is
// binary, and consumers want to hand it straight to os.WriteFile or a
// crypto package without a conversion on every use.
type goGenerator struct{}

func (goGenerator) Ext() string { return "go" }

func (goGenerator) Generate(w io.Writer, data []byte, m Meta) error {
	name := Pascal(m.Name)
	pkg := m.Pkg
	if pkg == "" {
		pkg = "main"
	}

	bw := bufio.NewWriterSize(w, 1<<16)

	// This exact wording is the convention the Go toolchain recognises to
	// mark a file as generated and leave it out of lint runs.
	fmt.Fprintf(bw, "// Code generated by bin2source. DO NOT EDIT.\n\n")
	fmt.Fprintf(bw, "package %s\n\n", pkg)

	// The banner above already says the file is generated, so the shared
	// comment is only worth emitting when it carries details about the
	// pipeline: a codec or a cipher. With neither, it would only repeat the
	// line above it.
	if m.Codec != "" || m.Cipher != "" || m.Base64 {
		lines := metaLines(m, func(suffix string) string {
			return joinedIdent(name, "", suffix, Pascal)
		})[1:] // drop the duplicate "generated by" line
		writeSlashComment(bw, lines, "")
		fmt.Fprint(bw, "\n")
	}

	if m.Base64 {
		// A string constant rather than a byte slice: the payload is text until
		// the consumer decodes it once. Nothing derives the length any more, so
		// it is written down instead of measured.
		fmt.Fprintf(bw, "const %s = ", name+Pascal("b64"))
		writeBase64Chunks(bw, data, "", "\t", " +")
		fmt.Fprintf(bw, "\n")
		fmt.Fprintf(bw, "const %s = %d\n\n", name+"Len", len(data))
	} else {
		fmt.Fprintf(bw, "var %s = []byte{\n", name)
		writeHexArray(bw, data, "\t")
		fmt.Fprintf(bw, "}\n\n")
		fmt.Fprintf(bw, "var %s = len(%s)\n\n", name+"Len", name)
	}

	if m.Codec != "" {
		// Raw DEFLATE does not record the size the inflated data will need.
		// A const rather than a var: unlike the length above, this one is
		// known without consulting the array.
		writeIntConst(bw, "const "+name+"RawLen", m.RawLen, "", "")
	}

	// Strings, not [32]byte: they read and compare as the hex digests that
	// sha256sum prints, and need no helper to be turned into text. One per
	// stage of the pipeline, so a failure can be pinned to a step.
	writeStageDigests(bw, m, func(suffix string) string {
		return "const " + name + Pascal(suffix)
	}, "", "", "", " ", "", false)
	return bw.Flush()
}
