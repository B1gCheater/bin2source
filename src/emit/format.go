package emit

import (
	"bufio"
	"encoding/base64"
	"fmt"
	"strings"

	"bin2source/src/crypt"
)

const (
	// hexDigits is lowercase on purpose: it matches the 0xNN array literals.
	hexDigits = "0123456789abcdef"

	// bytesPerLine is how many array elements go on one source line. 256 keeps
	// large payloads compact (about 1536 columns); it stays under the 4095
	// character logical line length C99 requires compilers to accept.
	bytesPerLine = 256

	// hexBytesPerLine is the Python equivalent: 32 bytes is 64 hex characters,
	// which fits comfortably inside one quoted string.
	hexBytesPerLine = 32

	// base64CharsPerLine is how many characters of base64 text go on one
	// source line. A multiple of four keeps every chunk on whole base64
	// quanta, and it is longer than the digest lines above so each line spends
	// a smaller share of itself on quotes, indentation and glue.
	base64CharsPerLine = 76
)

// metaLines builds the comment body shared by every language.
//
// The lines are listed in the order the pipeline applies them, so reading the
// comment top to bottom describes how the input became the array. Details are
// only emitted for the steps that actually ran: there is deliberately no size
// line, because the length is exposed as code instead, so it can never drift
// away from the array it describes.
//
// ident maps a suffix to the identifier it is declared under, so the second
// half of the comment can name the constants it is describing. The five
// languages disagree on casing, so each one passes its own.
func metaLines(m Meta, ident func(suffix string) string) []string {
	lines := []string{"generated by bin2source - do not edit"}
	if m.Codec == "" && m.Cipher == "" && !m.Base64 {
		return lines
	}

	if m.Codec != "" {
		// The wire word is load bearing: the codec name alone does not say
		// whether a zlib or gzip wrapper is in the way, and a consumer's
		// decoder has to know. The label is padded to line up with the iv
		// and key lines below.
		lines = append(lines, fmt.Sprintf("%-7s : %s, level %d", m.Codec, m.CodecWire, m.Level))
	}

	if m.Cipher != "" {
		cipher := m.Cipher
		if m.Cipher == crypt.ModeCBC {
			cipher += " (PKCS#7)"
		}
		ivPos := "comment only"
		if m.IVInArray {
			ivPos = "array[0:16]"
		}
		lines = append(lines,
			cipher,
			"iv      : "+m.IVHex+"  ("+ivPos+")",
			"key     : "+m.KeyHex,
		)
	}

	if m.Base64 {
		// The last line, because it is the last step: the bytes the lines above
		// describe are what the text below decodes to. Naming the alphabet
		// matters, because base64 comes in several flavours and the URL safe one
		// swaps + and / for - and _ and would not decode with the usual tables.
		lines = append(lines, "base64  : RFC 4648 standard, padded")
	}

	// A blank line, because the lines above describe the pipeline that made
	// the array and the ones below describe the constants that follow it.
	lines = append(lines, "")
	return append(lines, constantNotes(m, ident)...)
}

// constantNotes describes what each constant the generator is about to write
// holds.
//
// Once the payload is more than a copy of the file, the names stop being
// self explanatory and the comment has to say which stage each one belongs to.
// "logo_png_sha256" reads like the digest of the array called logo_png, and it
// is not: that one is logo_png_array_sha256. The plain suffix is the input
// file, before anything was done to it, and there is no way to infer that from
// the identifier next to an array of the same name.
//
// The descriptions never carry a value. A digest or a length written in a
// comment is a second copy of the truth that can drift from the constant below
// it, so the comment says what each one means and leaves the numbers to code.
func constantNotes(m Meta, ident func(suffix string) string) []string {
	type note struct{ name, desc string }

	// The steps the input went through, so each description can name only the
	// ones that ran. Saying "before encrypting" about a payload that was never
	// encrypted is noise, and noise in a comment is how people learn to skip
	// reading them.
	steps := ""
	switch {
	case m.Codec != "" && m.Cipher != "":
		steps = ", before compressing or encrypting"
	case m.Codec != "":
		steps = ", before compressing"
	case m.Cipher != "":
		steps = ", before encrypting"
	}

	notes := []note{
		{ident(arraySuffix(m)), arrayDesc(m)},
		{ident("len"), lenDesc(m)},
	}
	if m.Codec != "" {
		notes = append(notes, note{ident("raw_len"),
			"bytes the input file held, before compressing"})
	}
	notes = append(notes, note{ident("sha256"),
		"digest of the input file" + steps})
	if m.CodecSumHex != "" {
		after := "digest of the " + m.Codec + " output"
		if m.Cipher != "" {
			after += ", after compressing, before encrypting"
		}
		notes = append(notes, note{ident(m.Codec + "_sha256"), after})
	}
	if m.ArraySumHex != "" {
		iv := ""
		if m.IVInArray {
			iv = ", the IV included"
		}
		what := "the array's own bytes"
		if m.Base64 {
			what = "the bytes the base64 text decodes to"
		}
		notes = append(notes, note{ident("array_sha256"), "digest of " + what + iv})
	}

	width := 0
	for _, n := range notes {
		if len(n.name) > width {
			width = len(n.name)
		}
	}

	lines := []string{"Constants:"}
	for _, n := range notes {
		lines = append(lines, "  "+n.name+strings.Repeat(" ", width-len(n.name)+2)+n.desc)
	}
	return lines
}

// arraySuffix is the suffix the payload constant carries. With base64 the
// constant is the text, so it says so in its name; without it the constant is
// the payload itself and the plain name is the whole identifier.
func arraySuffix(m Meta) string {
	if m.Base64 {
		return "b64"
	}
	return ""
}

// lenDesc says what the length constant counts. It stays the number of bytes
// the payload holds, never the number of characters the text is written with,
// because it exists to size a buffer.
func lenDesc(m Meta) string {
	if m.Base64 {
		return "bytes the base64 text decodes to"
	}
	return "bytes the array holds"
}

// arrayDesc says what the array holds, in the same order the pipeline built
// it, so a consumer can tell from the comment alone what they have to undo.
//
// The cipher is named by its mode constant, AES256CBC, which is the same
// spelling the line above uses. Rewriting it as AES-256-CBC here would be
// tidier to read but would leave two names for one thing in the same comment.
func arrayDesc(m Meta) string {
	body := "the input file"
	if m.Codec != "" {
		body = m.Codec + " output"
	}
	desc := "the array: " + body
	if m.Base64 {
		desc = "the array: base64 text of " + body
	}
	if m.Cipher != "" {
		desc += ", encrypted with " + m.Cipher
	}
	if m.IVInArray {
		desc += ", led by its 16 byte IV"
	} else if m.Cipher != "" {
		desc += ", with the IV in the comment above"
	}
	return desc
}

// The helpers below take a *bufio.Writer and return nothing. bufio.Writer
// remembers the first error and hands it back from Flush, so generators only
// have to check the single Flush at the end.

// The three comment writers below treat an empty line as a blank separator
// rather than a line with nothing on it. Writing the marker and padding it
// would leave a trailing space after the star or the slashes, which is the
// sort of thing a whitespace checker in someone's CI reports on a file they
// did not write.

func writeBlockComment(w *bufio.Writer, lines []string) {
	w.WriteString("/*\n")
	for _, l := range lines {
		if l == "" {
			w.WriteString(" *\n")
			continue
		}
		w.WriteString(" * ")
		w.WriteString(l)
		w.WriteByte('\n')
	}
	w.WriteString(" */\n")
}

func writeSlashComment(w *bufio.Writer, lines []string, indent string) {
	for _, l := range lines {
		w.WriteString(indent)
		if l == "" {
			w.WriteString("//\n")
			continue
		}
		w.WriteString("// ")
		w.WriteString(l)
		w.WriteByte('\n')
	}
}

func writeHashComment(w *bufio.Writer, lines []string) {
	for _, l := range lines {
		if l == "" {
			w.WriteString("#\n")
			continue
		}
		w.WriteString("# ")
		w.WriteString(l)
		w.WriteByte('\n')
	}
}

// writeHexArray writes data as 0xNN elements, bytesPerLine of them per line.
//
// Every line ends with a comma, including the last one. Go rejects a newline
// before the closing brace of a composite literal unless the previous element
// is followed by a comma, and C, C++ and Rust all accept the trailing comma,
// so one shape works everywhere.
func writeHexArray(w *bufio.Writer, data []byte, indent string) {
	line := make([]byte, 0, len(indent)+bytesPerLine*7+1)
	for i := 0; i < len(data); i += bytesPerLine {
		end := min(i+bytesPerLine, len(data))

		line = append(line[:0], indent...)
		for j := i; j < end; j++ {
			if j > i {
				line = append(line, ' ')
			}
			b := data[j]
			line = append(line, '0', 'x', hexDigits[b>>4], hexDigits[b&0x0f], ',')
		}
		line = append(line, '\n')

		w.Write(line)
	}
}

// writeHexString writes data as double quoted hex literals, one per line.
// Languages that concatenate adjacent string literals can stack them without
// a separator.
func writeHexString(w *bufio.Writer, data []byte, indent string) {
	hex := make([]byte, 2*len(data))
	for i, b := range data {
		hex[2*i] = hexDigits[b>>4]
		hex[2*i+1] = hexDigits[b&0x0f]
	}
	// No separator: the parser glues the literals together anyway, and
	// anything between them would be trailing whitespace on the line.
	writeHexQuoted(w, hex, indent, "")
}

// writeHexQuoted writes text, which must already be hex digits, as double
// quoted hex literals of hexBytesPerLine bytes each, one per line. sep is
// placed between two literals but never after the last one, so no line carries
// trailing blanks.
//
// A separator is only ever emitted when a value spans more than one line,
// which the 64 character digest never does; it is still the caller's to
// state, because languages disagree on what stacking literals means. C, C++
// and Python concatenate adjacent string literals, so those pass whitespace
// (verified: gcc accepts a wrapped, newline separated pair inside the
// parentheses this package writes). Rust does not concatenate literals at
// all, so its generator writes each digest as a single literal instead.
func writeHexQuoted(w *bufio.Writer, text []byte, indent, sep string) {
	if len(text) == 0 {
		w.WriteString(indent)
		w.WriteString(`""` + "\n")
		return
	}

	// A chunk is hexBytesPerLine bytes, which is twice as many characters.
	charsPerLine := 2 * hexBytesPerLine
	line := make([]byte, 0, len(indent)+charsPerLine+4)
	for i := 0; i < len(text); i += charsPerLine {
		end := min(i+charsPerLine, len(text))

		line = append(line[:0], indent...)
		line = append(line, '"')
		line = append(line, text[i:end]...)
		line = append(line, '"')
		if end < len(text) && sep != "" {
			line = append(line, sep...)
		}
		line = append(line, '\n')

		w.Write(line)
	}
}

// writeBase64Chunks writes data as base64 text, base64CharsPerLine characters
// per line, each line a complete double quoted literal.
//
// firstIndent prefixes the first line and indent prefixes the rest, because Go
// starts the value on the line holding the "=" while every other language
// starts it on a line of its own; sep is written after the closing quote of
// every line but the last, which is where Go puts its "+".
//
// The text is emitted as several literals rather than one enormous line so the
// generated file stays readable and no compiler's limit on the length of a
// single string literal is ever in play.
func writeBase64Chunks(w *bufio.Writer, data []byte, firstIndent, indent, sep string) {
	text := base64.StdEncoding.EncodeToString(data)
	if text == "" {
		w.WriteString(firstIndent)
		w.WriteString(`""` + "\n")
		return
	}

	line := make([]byte, 0, len(indent)+base64CharsPerLine+len(sep)+4)
	for i := 0; i < len(text); i += base64CharsPerLine {
		end := min(i+base64CharsPerLine, len(text))

		line = line[:0]
		if i == 0 {
			line = append(line, firstIndent...)
		} else {
			line = append(line, indent...)
		}
		line = append(line, '"')
		line = append(line, text[i:end]...)
		line = append(line, '"')
		if end < len(text) {
			line = append(line, sep...)
		}
		line = append(line, '\n')

		w.Write(line)
	}
}

// writeHexLiteral writes text as one double quoted literal with no line break
// after it, so a statement terminator can follow on the same line. The digest
// is short enough for that; see writeSha256Const.
func writeHexLiteral(w *bufio.Writer, text string) {
	w.WriteByte('"')
	w.WriteString(text)
	w.WriteByte('"')
}

// writeIntConst writes an integer constant.
//
// decl is everything up to the "=", name, type and qualifiers included: the
// five languages put those in different places, so the caller spells its own.
// semi is the statement terminator, empty for Go and Python.
func writeIntConst(w *bufio.Writer, decl string, n int, indent, semi string) {
	fmt.Fprintf(w, "%s%s = %d%s\n\n", indent, decl, n, semi)
}

// writeStageDigests writes the digest constants for every stage of the
// pipeline that produced a distinct run of bytes.
//
// The set is decided by the flags, not by a count, so a consumer can rely on
// the rule: the input digest is always written, the codec digest appears
// exactly when the payload was compressed, and the array digest exactly when
// it was encrypted. No digest is ever written twice under two names, because
// each name is reserved for the one boundary it checks.
//
// decl maps a suffix such as "sha256" or "array_sha256" to the complete
// declaration up to the "=", since the identifier casing differs per language:
// C and C++ keep "logo_png_sha256", Go wants "LogoPngSha256", Rust and Python
// "LOGO_PNG_SHA256".
func writeStageDigests(w *bufio.Writer, m Meta, decl func(suffix string) string, typ, indent, litIndent, sep, semi string, wrap bool) {
	writeSha256Const(w, decl("sha256"), typ, m.Sha256Hex, indent, litIndent, sep, semi, wrap)
	if m.CodecSumHex != "" {
		writeSha256Const(w, decl(m.Codec+"_sha256"), typ, m.CodecSumHex, indent, litIndent, sep, semi, wrap)
	}
	if m.ArraySumHex != "" {
		writeSha256Const(w, decl("array_sha256"), typ, m.ArraySumHex, indent, litIndent, sep, semi, wrap)
	}
}

// writeSha256Const writes the declaration whose value is the digest.
//
// name is the identifier with its qualifiers, typ is whatever the language
// puts after it ("[]" for C and C++, ": &str" for Rust, empty for Go and
// Python), hex is the 64 character lowercase digest, indent is the statement
// prefix, litIndent is the indentation of the wrapped literal's own line, sep
// joins the two literals when a wrapped value spans more than one line (" "
// for the languages that concatenate adjacent literals; see writeHexQuoted),
// semi is the statement terminator ("" for Go and Python), and wrap puts the
// literals
// inside parentheses on their own lines.
//
// litIndent is a parameter rather than indent plus a tab because the
// languages disagree: C and C++ indent continuation lines with a tab while
// Python uses four spaces, and a tab in a parenthesised continuation next to
// four space indentation elsewhere in the same module is mixed indentation,
// which linters flag.
//
// Go is the one language that needs wrap disabled: a parenthesised expression
// may not start on the line after the "=" there, and rustc warns about one
// that does not need to be there.
//
// The value is the lowercase hex text rather than the 32 raw bytes because it
// compares against sha256sum or hashlib output directly and cannot be mistaken
// for part of the payload array sitting next to it.
func writeSha256Const(w *bufio.Writer, name, typ, hex, indent, litIndent, sep, semi string, wrap bool) {
	// On a single line the literal is written without a trailing newline so
	// the terminator can join it; in the wrapped form each line is complete
	// and the closing bracket gets its own line.
	if !wrap {
		fmt.Fprintf(w, "%s%s%s = ", indent, name, typ)
		writeHexLiteral(w, hex)
		fmt.Fprintf(w, "%s\n\n", semi)
		return
	}

	fmt.Fprintf(w, "%s%s%s = (\n", indent, name, typ)
	writeHexQuoted(w, []byte(hex), litIndent, sep)
	fmt.Fprintf(w, ")%s\n\n", semi)
}
